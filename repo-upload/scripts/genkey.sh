#!/bin/bash
# Раннер запускает тело shell: bash как bash --noprofile --norc -eo pipefail.
# action.yml теперь зовёт этот файл отдельным bash, опции он не наследует —
# задаём их здесь, иначе шаг молча продолжал бы работу после ошибки.
set -eo pipefail
# Имя RANDOM для идентификатора ключа не годится: в скрипте встроенная
# переменная bash перекрывает экспортированную, и путь к ключу указал бы
# на несуществующий файл. Справа — генератор bash, как и прежде.
echo "KEY_ID=ID_$((RANDOM % 1000000))" >> "${GITHUB_ENV}"
echo "HOME=${HOME}" >> "${GITHUB_ENV}"
mkdir -p "${HOME}/.ssh"

